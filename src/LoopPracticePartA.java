
public class LoopPracticePartA {
    public static void main(String[] args) {


        int i;


        for (i = 1; i <= 20; i++) {
            System.out.print(i);
        }
        System.out.print("\n");


        for (i = 0; i <= 20; i = i + 2) {
            System.out.print(i);
        }
        System.out.print("\n ");
    }
}
